from __future__ import annotations
from typing import Dict, Any, List, Optional, Iterable, Tuple
from pathlib import Path
import json
import csv

from ..io.format_adapter import load_bundle_from_file
from ..schemas.base import SampleMetadata, StudyMetadata
from ..context.context_builder import compose_llm_context, ContextOpts
from ..ontologies.mapper import get_mapper

DEFAULT_FIELDS = [
    "organism", "tissue", "cell_type", "cell_line", "treatment", "disease",
    "genotype", "strain", "age", "sex", "developmental_stage"
]


def _guidelines_text(profile: str, opts: ContextOpts, fields: List[str]) -> str:
    return f"""
# Gold-Set Curation Guide

This packet was generated by omics-extractor with context profile: `{profile}`.
The goal is to produce a robust, reproducible evaluation set that mirrors exactly
what the LLM sees during enrichment.

What you will curate
- Target fields: {', '.join(fields)}
- For each sample, review the `llm_context` (study + sample context blocks) and fill the `gold_*` columns or fields.
- If a field is not present or cannot be determined confidently, leave it blank.

Rules of the road
- Use canonical, lowercase labels (e.g., `liver`, `hek293`, `fibroblast`).
- Prefer ontology shortlist IDs when shown (choose a label; IDs are stored separately).
- Do not infer beyond evidence shown in context. Conservative beats speculative.
- If multiple tissues/conditions are described, choose the most specific applicable to the sample.
- If a sample is out of scope or ambiguous, leave the gold field blank.

Context parity (what the model sees)
- Profile `{profile}` includes: overall design (if present), GEO protocols (growth/extract/treatment), GEO source name,
  BioProject type/scope, PubMed MeSH (if available), BioSample description (only when the source is BioSample),
  raw characteristics and technical (SRA) metadata.
- Truncation: {'off (no truncation)' if (getattr(opts,'truncate_chars',0) or 0) == 0 else f'on, per-block {opts.truncate_chars} chars'}.
- Channels: {'merged (CH1:/CH2: inline)' if getattr(opts,'merge_channels',True) else 'separate (distinct fields)'}.

How to record values
- JSONL: leave `targets` as nulls; curate externally and save sidecar TSV, or use TSV/CSV mode below.
- TSV/CSV: edit only the `gold_*` columns. Do not change context columns.
- Keep plain text labels (we will map to ontologies in evaluation).

Quality checklist
- [ ] Coverage: only fill fields that are clearly supported by the context.
- [ ] Consistency: same spelling across samples of the same project.
- [ ] Specificity: prefer specific terms over generic ones (e.g., `primary hepatocyte` > `liver cell`).
- [ ] Ambiguity: if conflicted, leave blank rather than guessing.

Submission
- Save the edited file in place. Do not change column headers.
""".strip() + "\n"


def _prov_val(sample: SampleMetadata, field: str) -> Optional[str]:
    obj = getattr(sample, field, None)
    try:
        return obj.value if obj else None
    except Exception:
        return None


def _as_context(study: StudyMetadata, sample: SampleMetadata) -> Dict[str, Any]:
    return {
        "study_title": getattr(study.title, 'value', None),
        "study_description": getattr(study.description, 'value', None),
        "abstract": getattr(study.paper_abstract, 'value', None) if getattr(study, 'paper_abstract', None) else None,
        "journal": getattr(study.journal, 'value', None) if getattr(study, 'journal', None) else None,
        "authors": getattr(study, 'authors', None),
        "publication_date": getattr(study, 'publication_date', None),
        "sample_title": getattr(sample.sample_title, 'value', None) if getattr(sample, 'sample_title', None) else None,
        "sample_description": getattr(sample.sample_description, 'value', None) if getattr(sample, 'sample_description', None) else None,
        "raw_characteristics": sample.raw_characteristics,
        "technical_context": sample.technical_context,
    }


def _shortlists(sample: SampleMetadata, k: int) -> Dict[str, List[Dict[str, Any]]]:
    out: Dict[str, List[Dict[str, Any]]] = {}
    if not k:
        return out
    mapper = get_mapper()
    def pick(raw: Optional[str], onto: str) -> List[Dict[str, Any]]:
        if not raw:
            return []
        try:
            res = mapper.ols_client.search(raw, onto)
            if not res:
                return []
            label, obo_id, conf = res
            return [{"label": label, "id": obo_id, "score": conf}]
        except Exception:
            return []
    rc = sample.raw_characteristics or {}
    for field, onto in (('tissue','uberon'),('cell_type','cl'),('treatment','efo')):
        raw = rc.get(field) or rc.get(field.replace('_',' '))
        cand = pick(raw, onto)
        if cand:
            out[field] = cand[:k]
    return out


def prepare_goldset(
    inputs: Iterable[Path],
    out_path: Path,
    fmt: str = 'jsonl',
    fields: Optional[List[str]] = None,
    shortlist_k: int = 0,
    context_profile: str = 'extended',
    context_opts: Optional[ContextOpts] = None,
    include_sra_runs: bool = False,
) -> Tuple[int, Path]:
    fields = fields or list(DEFAULT_FIELDS)
    records: List[Dict[str, Any]] = []
    context_opts = context_opts or ContextOpts()

    for p in inputs:
        bundle = load_bundle_from_file(p)
        study = bundle["study"]
        for sid, sample in bundle["samples"].items():
            runs_for_sample: List[Dict[str, Any]] = []
            if include_sra_runs:
                try:
                    for r in bundle.get("runs", []):
                        if getattr(r, 'sample_id', None) == sid or (isinstance(r, dict) and r.get('sample_id') == sid):
                            rd = r if isinstance(r, dict) else r.model_dump()
                            runs_for_sample.append({
                                "run_id": rd.get("run_id"),
                                "library_strategy": (rd.get("library_strategy") or {}).get("value") if isinstance(rd.get("library_strategy"), dict) else rd.get("library_strategy"),
                                "library_source": rd.get("library_source"),
                                "library_selection": rd.get("library_selection"),
                                "library_layout": rd.get("library_layout"),
                                "platform": rd.get("platform"),
                                "instrument_model": rd.get("instrument_model"),
                                "read_count": rd.get("read_count"),
                                "base_count": rd.get("base_count"),
                                "run_date": rd.get("run_date"),
                            })
                except Exception:
                    runs_for_sample = []
            rec: Dict[str, Any] = {
                "ids": {
                    "bioproject_id": study.bioproject_id,
                    "sample_id": sid,
                },
                # NOTE: sra_runs is a curator-only assist; it is NOT fed to the LLM prompt.
                "llm_context": compose_llm_context(study, sample, profile=context_profile, opts=context_opts) | ({"sra_runs": runs_for_sample} if runs_for_sample else {}),
                "targets": {f: None for f in fields},
                "current_values": {f: _prov_val(sample, f) for f in fields},
                "ontology_shortlists": _shortlists(sample, shortlist_k),
            }
            records.append(rec)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fmt_l = (fmt or 'jsonl').lower()
    guide_path = out_path.with_suffix(out_path.suffix + ".GUIDE.md")
    if fmt_l == 'jsonl':
        with open(out_path, 'w') as f:
            for r in records:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    elif fmt_l in ('tsv', 'csv'):
        cols = [
            'bioproject_id','sample_id','study_title','study_description','sample_title','sample_description',
            'context_profile','geo_overall_design','geo_source_name','geo_protocols_growth','geo_protocols_extract','geo_protocols_treatment',
            'bioproject_summary','pubmed_mesh','biosample_description','raw_characteristics_json','technical_context_json','sra_runs_json','ontology_shortlists_json','current_values_json'
        ] + [f'gold_{f}' for f in fields]
        delimiter = ',' if fmt_l == 'csv' else "	"
        with open(out_path, 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=cols, delimiter=delimiter)
            w.writeheader()
            for r in records:
                row = {
                    'bioproject_id': r['ids']['bioproject_id'],
                    'sample_id': r['ids']['sample_id'],
                    'study_title': r['llm_context'].get('study_title'),
                    'study_description': r['llm_context'].get('study_description'),
                    'sample_title': r['llm_context'].get('sample_title'),
                    'sample_description': r['llm_context'].get('sample_description'),
                    'context_profile': context_profile,
                    'geo_overall_design': r['llm_context'].get('geo_overall_design') or '',
                    'geo_source_name': r['llm_context'].get('geo_source_name') or '',
                    'geo_protocols_growth': (r['llm_context'].get('geo_protocols') or {}).get('growth', ''),
                    'geo_protocols_extract': (r['llm_context'].get('geo_protocols') or {}).get('extract', ''),
                    'geo_protocols_treatment': (r['llm_context'].get('geo_protocols') or {}).get('treatment', ''),
                    'bioproject_summary': r['llm_context'].get('bioproject_summary') or '',
                    'pubmed_mesh': r['llm_context'].get('pubmed_mesh') or '',
                    'biosample_description': r['llm_context'].get('biosample_description') or '',
                    'raw_characteristics_json': json.dumps(r['llm_context'].get('raw_characteristics') or {}, ensure_ascii=False),
                    'technical_context_json': json.dumps(r['llm_context'].get('technical_context') or {}, ensure_ascii=False),
                    'sra_runs_json': json.dumps(r['llm_context'].get('sra_runs') or [], ensure_ascii=False),
                    'ontology_shortlists_json': json.dumps(r.get('ontology_shortlists') or {}, ensure_ascii=False),
                    'current_values_json': json.dumps(r.get('current_values') or {}, ensure_ascii=False),
                }
                for fkey in fields:
                    row[f'gold_{fkey}'] = ''
                w.writerow(row)
    else:
        raise ValueError(f"Unsupported format: {fmt}")
    # Write curation guidelines next to the packet
    with open(guide_path, 'w') as gf:
        gf.write(_guidelines_text(context_profile, context_opts, fields))

    return len(records), guide_path
